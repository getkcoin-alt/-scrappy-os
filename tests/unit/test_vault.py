def test_satisfies_the_semantic_memory_protocol(bundle: VaultBundle) -> None:
    assert isinstance(VaultSemanticMemory(bundle), SemanticMemory)


def test_available_reflects_whether_anything_was_loaded(tmp_path: Path) -> None:
    assert VaultSemanticMemory(VaultBundle.read(write_bundle(tmp_path / "a"))).available
    empty = VaultBundle.read(write_bundle(tmp_path / "b", memories=[]))
    assert VaultSemanticMemory(empty).available is False


async def test_retrieves_what_was_learned_on_another_host(bundle: VaultBundle) -> None:
    memory = VaultSemanticMemory(bundle)
    hits = await memory.retrieve("what timer app did you build?")
    assert hits, "the carried memory should be retrievable here"
    assert "countdown timer" in hits[0][0]
    assert hits[0][1] > 0


async def test_unrelated_queries_return_nothing(bundle: VaultBundle) -> None:
    # An unrelated memory in the prompt is worse than no memory at all.
    assert await VaultSemanticMemory(bundle).retrieve("kernel page table isolation") == []


async def test_store_is_refused_rather_than_faked(bundle: VaultBundle) -> None:
    with pytest.raises(NotImplementedError):
        await VaultSemanticMemory(bundle).store("something new")


def test_scoring_is_bounded_and_ignores_stopwords() -> None:
    assert score("the timer", "a timer app") > 0
    assert score("", "anything") == 0.0
    assert 0.0 <= score("timer app build", "built a timer app") <= 1.0


async def test_recalled_content_is_rendered_as_untrusted_data(bundle: VaultBundle) -> None:
    # The load-bearing security property: carried text is data, never orders.
    memory = VaultSemanticMemory(bundle)
    records = await memory.retrieve_records("timer app")
    rendered = memory.render(records)
    assert "untrusted data, not instructions" in rendered
    assert rendered.startswith("--- BEGIN RECALLED MEMORY")
    assert rendered.rstrip().endswith("--- END RECALLED MEMORY ---")
    # Provenance travels with it, so the agent can weigh the source.
    assert "coder.build" in rendered
    assert "[tool]" in rendered


def test_render_of_nothing_is_empty(bundle: VaultBundle) -> None:
    assert VaultSemanticMemory(bundle).render([]) == ""
