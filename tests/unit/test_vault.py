def test_identity_renders_into_prompt_text(bundle: VaultBundle) -> None:
    text = bundle.render_identity()
    assert "You are Scrappy Singh." in text
    assert "Karnveer Singh" in text and "'Boss'" in text
    assert "financial freedom through automation" in text
    assert "Never claim a task is done without verifiable proof." in text


def test_identity_carries_secret_names_not_values(bundle: VaultBundle) -> None:
    assert bundle.identity.secret_refs == ["llm_api_key", "elevenlabs_api_key"]
    assert "sk-" not in json.dumps(bundle.identity.model_dump())


