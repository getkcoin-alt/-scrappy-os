def test_reads_a_bundle_written_by_another_implementation(bundle: VaultBundle) -> None:
    assert bundle.identity.name == "Scrappy Singh"
    assert bundle.identity.operator.address_as == "Boss"
    assert bundle.identity.revision == 7
    assert len(bundle.memories) == 2
    assert bundle.summary()["vault_id"] == "karnveer-vault"


def test_refuses_an_unknown_major(tmp_path: Path) -> None:
    directory = write_bundle(
        tmp_path / "v", manifest={**MANIFEST, "protocol_version": "2.0.0"}
    )
    with pytest.raises(IncompatibleVault):
        VaultBundle.read(directory)


def test_accepts_a_newer_minor(tmp_path: Path) -> None:
    # Forward compatible within a major - unknown fields are preserved, so a
    # newer minor is safe to read.
    directory = write_bundle(
        tmp_path / "v", manifest={**MANIFEST, "protocol_version": "1.9.2"}
    )
    assert VaultBundle.read(directory).identity.name == "Scrappy Singh"


def test_rejects_a_directory_that_is_not_a_bundle(tmp_path: Path) -> None:
    (tmp_path / "empty").mkdir()
    with pytest.raises(MalformedVault):
        VaultBundle.read(tmp_path / "empty")
    with pytest.raises(MalformedVault):
        VaultBundle.read(tmp_path / "missing")


def test_unknown_fields_survive_the_round_trip(tmp_path: Path) -> None:
    # An older reader must not destroy a newer writer's data.
    future = [{**MEMORIES[0], "confidence": 0.4, "x": {"host": "linux-box"}}]
    directory = write_bundle(tmp_path / "v", memories=future)
    record = VaultBundle.read(directory).memories[0]
    assert record.model_dump()["confidence"] == 0.4
    assert record.x == {"host": "linux-box"}


def test_a_single_corrupt_line_does_not_lose_the_rest(tmp_path: Path) -> None:
    directory = write_bundle(tmp_path / "v")
    with (directory / "memories.jsonl").open("a") as handle:
        handle.write("{ not json\n")
    assert len(VaultBundle.read(directory).memories) == 2


def test_no_embeddings_are_expected_or_required(bundle: VaultBundle) -> None:
    # The portability rule: vectors never travel, so nothing here reads one.
    for record in bundle.memories:
        assert "embedding" not in record.model_dump()


def test_expired_memories_are_not_live(tmp_path: Path) -> None:
    stale = [{**MEMORIES[0], "expires_at": "2026-01-01T00:00:00+00:00"}, MEMORIES[1]]
    bundle = VaultBundle.read(write_bundle(tmp_path / "v", memories=stale))
    live = bundle.live_memories(now_iso="2026-08-18T00:00:00+00:00")
    assert [m.id for m in live] == ["m2"]


