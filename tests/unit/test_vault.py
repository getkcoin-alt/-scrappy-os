"""Consuming a Vault Zeta bundle.

The fixtures here are hand-written to the *spec*, not generated by the producer -
that is the point of a protocol. If these pass against a bundle another
implementation wrote, the format is real.
"""

from __future__ import annotations

import json
from pathlib import Path

import pytest

from scrappy_os.memory.base import SemanticMemory
from scrappy_os.vault import (
    IncompatibleVault,
    MalformedVault,
    VaultBundle,
    VaultSemanticMemory,
)
from scrappy_os.vault.semantic import score

# --------------------------------------------------------------------------
# fixtures
# --------------------------------------------------------------------------

MANIFEST = {
    "protocol_version": "1.0.0",
    "vault_id": "karnveer-vault",
    "exported_at": "2026-08-18T19:00:00+00:00",
    "exported_by": "Karnveers-MacBook-Air",
    "counts": {"memories": 2, "directives": 1},
    "includes_episodes": False,
}

IDENTITY = {
    "name": "Scrappy Singh",
    "operator": {"handle": "karnveer", "name": "Karnveer Singh", "address_as": "Boss"},
    "mission": {"statement": "financial freedom through automation", "target_date": "2026-11-23"},
    "persona": ["Sharp, direct, no fluff. Lead with the recommendation."],
    "invariants": ["Never claim a task is done without verifiable proof."],
    "secret_refs": ["llm_api_key", "elevenlabs_api_key"],
    "revision": 7,
}

MEMORIES = [
    {
        "id": "m1",
        "kind": "factual",
        "content": "Built a countdown timer app for Karnveer; it opens index.html.",
        "content_sha256": "abc",
        "importance": 0.75,
        "source": "coder.build",
        "learned_at": "2026-08-18T18:41:00+00:00",
        "learned_by": "Karnveers-MacBook-Air",
        "expires_at": None,
        "trust": "tool",
    },
    {
        "id": "m2",
        "kind": "semantic",
        "content": "Karnveer prefers direct answers with no hedging.",
        "importance": 0.9,
        "source": "agent:memory_keeper",
        "learned_at": "2026-08-01T10:00:00+00:00",
        "learned_by": "Karnveers-MacBook-Air",
        "expires_at": None,
        "trust": "operator",
    },
]


def write_bundle(directory: Path, *, manifest=None, memories=None) -> Path:
    directory.mkdir(parents=True, exist_ok=True)
    (directory / "manifest.json").write_text(json.dumps(manifest or MANIFEST))
    (directory / "identity.json").write_text(json.dumps(IDENTITY))
    (directory / "directives.jsonl").write_text(
        json.dumps({"id": "d1", "content": "Be direct.", "active": True}) + "\n"
    )
    (directory / "memories.jsonl").write_text(
        "\n".join(json.dumps(m) for m in (MEMORIES if memories is None else memories)) + "\n"
    )
    return directory


@pytest.fixture
def bundle(tmp_path: Path) -> VaultBundle:
    return VaultBundle.read(write_bundle(tmp_path / "vault"))


